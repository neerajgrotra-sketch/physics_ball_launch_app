// Writes components/feedback/playlist.ts: one entry for every music file in assets/music (MP3 or M4A), in name order. The app picks one
// of them for each session (components/feedback/music.ts). Runs before every web build (npm run web:setup), so adding music is just
// adding a file to assets/music; run it by hand (node scripts/make-playlist.mjs) for a native build.
//
// Each entry says which mode it's for (a file named asmr-… plays in ASMR mode, the rest in regular mode) and, when the track comes
// with a <name>.json from scripts/make-music.mjs, its exact loop length, which the web player uses to repeat it seamlessly.
//
// Phones get their own list, playlist.native.ts, of seamless WAV copies in assets/music/loops. An MP3 has a few milliseconds of encoder
// silence at each end, which iOS plays, so the loop hiccuped; the web decodes the whole file and loops it cleanly, so it keeps the MP3.
// The WAVs are made here with ffmpeg (which drops that padding) when it's installed, and committed; a track without one falls back to
// its MP3 on phones.
//
// But the iPhone's player still pauses whenever it loops a file, or moves to another copy, or hands over to a second player (0.62.2
// and 0.62.3 tried both): each time it sets the file up again. So what phones actually play is assets/music/long/<name>.m4a: the
// exact loop repeated to about LONG_SECONDS (ten minutes) in one AAC file, made here from the loop WAV. The repeats are joined sample
// for sample, so they're seamless; the player only jumps back at the end of the file. (ffmpeg's MP4 marks the encoder's start-up
// silence for players to skip, so it starts cleanly too.)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets', 'music');
const files = fs.readdirSync(dir).filter((f) => /\.(mp3|m4a)$/i.test(f)).sort();
if (files.length === 0) throw new Error('assets/music has no .mp3 or .m4a files: the game needs at least one track');

const meta = (f) => {
  const json = path.join(dir, f.replace(/\.(mp3|m4a)$/i, '.json'));
  return fs.existsSync(json) ? JSON.parse(fs.readFileSync(json, 'utf8')) : null;
};
const entry = (src, f) => `  { src: require('${src}'), loop: ${meta(f)?.loop ?? null}, asmr: ${/^asmr-/i.test(f)} },`;
const TYPE = `/** A music track: its file, its exact loop length in seconds (null: loop the whole file), and whether it's for ASMR mode. */
export interface Track { src: number; loop: number | null; asmr: boolean }`;
const lines = files.map((f) => entry(`../../assets/music/${f}`, f));
const out = `// Generated by scripts/make-playlist.mjs from the files in assets/music. Don't edit: add or remove music files instead.
${TYPE}

export const PLAYLIST: Track[] = [
${lines.join('\n')}
];
`;
fs.writeFileSync(path.join(root, 'components', 'feedback', 'playlist.ts'), out);

const loops = path.join(dir, 'loops');
fs.mkdirSync(loops, { recursive: true });
const loopFor = (f) => path.join(loops, f.replace(/\.(mp3|m4a)$/i, '.wav'));
for (const f of files) {
  const wav = loopFor(f);
  if (meta(f) && fs.existsSync(wav)) continue; // made by scripts/make-music.mjs, already a seamless loop
  if (fs.existsSync(wav) && fs.statSync(wav).mtimeMs >= fs.statSync(path.join(dir, f)).mtimeMs) continue;
  try {
    execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', path.join(dir, f), '-map', '0:a', '-ar', '44100', '-ac', '2', '-c:a', 'pcm_s16le', wav]);
  } catch {
    console.warn(`playlist: no ffmpeg, so ${f} has no seamless loop for phones (it plays the ${path.extname(f)}): install ffmpeg and run this again`);
  }
}
const LONG_SECONDS = 600;
const long = path.join(dir, 'long');
fs.mkdirSync(long, { recursive: true });
const longFor = (f) => path.join(long, f.replace(/\.(mp3|m4a)$/i, '.m4a'));
for (const f of files) {
  const wav = loopFor(f), m4a = longFor(f), loop = meta(f)?.loop;
  if (!loop || !fs.existsSync(wav)) continue;
  if (fs.existsSync(m4a) && fs.statSync(m4a).mtimeMs >= fs.statSync(wav).mtimeMs) continue;
  const copies = Math.max(2, Math.ceil(LONG_SECONDS / loop));
  try {
    execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-stream_loop', String(copies - 1), '-i', wav, '-c:a', 'aac', '-b:a', '96k', m4a]);
  } catch {
    console.warn(`playlist: no ffmpeg, so ${f} has no long copy for phones (it plays the loop WAV): install ffmpeg and run this again`);
  }
}
// Phones: the long copy where there is one (no loop length: the player just loops it), else the loop WAV, else the original file.
const native = files.map((f) => fs.existsSync(longFor(f))
  ? `  { src: require('../../assets/music/long/${path.basename(longFor(f))}'), loop: null, asmr: ${/^asmr-/i.test(f)} },`
  : entry(fs.existsSync(loopFor(f)) ? `../../assets/music/loops/${path.basename(loopFor(f))}` : `../../assets/music/${f}`, f));
fs.writeFileSync(path.join(root, 'components', 'feedback', 'playlist.native.ts'), `// Generated by scripts/make-playlist.mjs: the phone copies of assets/music, ten-minute seamless repeats (long/*.m4a). Don't edit.
// (The web uses playlist.ts.)
${TYPE}

export const PLAYLIST: Track[] = [
${native.join('\n')}
];
`);
console.log(`playlist: ${files.length} track${files.length === 1 ? '' : 's'} (${files.join(', ')})`);
