// Writes components/feedback/playlist.ts: one entry for every music file in assets/music (MP3 or M4A), in name order. The app picks one
// of them for each session (components/feedback/music.ts). Runs before every web build (npm run web:setup), so adding music is just
// adding a file to assets/music; run it by hand (node scripts/make-playlist.mjs) for a native build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets', 'music');
const files = fs.readdirSync(dir).filter((f) => /\.(mp3|m4a)$/i.test(f)).sort();
if (files.length === 0) throw new Error('assets/music has no .mp3 or .m4a files: the game needs at least one track');

const lines = files.map((f) => `  require('../../assets/music/${f}'),`);
const out = `// Generated by scripts/make-playlist.mjs from the files in assets/music. Don't edit: add or remove music files instead.
export const PLAYLIST: number[] = [
${lines.join('\n')}
];
`;
fs.writeFileSync(path.join(root, 'components', 'feedback', 'playlist.ts'), out);
console.log(`playlist: ${files.length} track${files.length === 1 ? '' : 's'} (${files.join(', ')})`);
